using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._RMC14.Vendors;

[GenerateTypedNameReferences]
public sealed partial class CMAutomatedVendorEntry : Control
{
    private static readonly Color RequiredFill = Color.FromHex("#251A0C");
    private static readonly Color RequiredBorder = Color.FromHex("#805300");
    private static readonly Color RecommendedFill = Color.FromHex("#102919");
    private static readonly Color RecommendedBorder = Color.FromHex("#3A9B52");

    public CMAutomatedVendorEntry()
    {
        RobustXamlLoader.Load(this);
    }

    internal void SetProduct(string name, bool required, bool recommended)
    {
        Panel.Button.Label.Text = recommended && !required ? $"★ {name}" : name;
        (Panel.Color, Panel.BorderColor) = (required, recommended) switch
        {
            (true, _) => (RequiredFill, RequiredBorder),
            (_, true) => (RecommendedFill, RecommendedBorder),
            _ => (CMAutomatedVendorPanel.DefaultColor, CMAutomatedVendorPanel.DefaultBorderColor),
        };
        Panel.HoveredColor = Panel.BorderColor;
        Panel.UpdateColor();
    }

    internal void SetAvailability(int? points, int? amount, bool disabled)
    {
        Amount.Text = points is { } price ? $"{price}P" : amount.ToString();
        Amount.Modulate = disabled ? Color.Red : Color.White;
        Panel.Button.Disabled = disabled;
    }
}
