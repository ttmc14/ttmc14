using System.Linq;
using System.Numerics;
using Content.Client._RMC14.Vendors;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._MC.Vending.UI;

[GenerateTypedNameReferences]
public sealed partial class MCVendorSectionView : BoxContainer
{
    internal bool Accessible { get; set; }

    public MCVendorSectionView()
    {
        RobustXamlLoader.Load(this);
    }

    internal void AlignColumns()
    {
        var rows = Rows.Children.Cast<CMAutomatedVendorEntry>();
        var iconSize = Vector2.Zero;
        var amountWidth = 0f;
        foreach (var row in rows)
        {
            foreach (var layer in row.Texture.Textures)
            {
                iconSize = Vector2.Max(iconSize, new Vector2(layer.Width, layer.Height) * row.Texture.TextureScale);
            }

            if (string.IsNullOrEmpty(row.Amount.Text))
                continue;

            row.Amount.Visible = true;
            row.Amount.SetWidth = float.NaN;
            row.Amount.Measure(new Vector2(float.PositiveInfinity));
            amountWidth = Math.Max(amountWidth, row.Amount.DesiredSize.X - row.Amount.Margin.SumHorizontal);
        }

        foreach (var row in rows)
        {
            row.Texture.SetSize = iconSize;
            row.Texture.Stretch = TextureRect.StretchMode.KeepCentered;
            row.Amount.Visible = amountWidth > 0;
            row.Amount.SetWidth = amountWidth;
        }
    }
}
