using System.Linq;
using System.Numerics;
using Content.Client._RMC14.Vendors;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._MC.Vending.UI;

[GenerateTypedNameReferences]
public sealed partial class MCVendorWindow : DefaultWindow
{
    private string[] _categories = [];
    private bool _tabbed;
    private string? _selected;

    public MCVendorWindow()
    {
        RobustXamlLoader.Load(this);
        Categories.OnItemSelected += args => SelectCategory(args.Id);
        Search.OnTextChanged += _ => ApplyFilter();
        ShowEmpty.OnToggled += _ => RefreshCategories(_tabbed);
    }

    internal void AlignColumns()
    {
        var rows = Sections.Children.Cast<MCVendorSectionView>()
            .Where(section => section.Accessible)
            .SelectMany(section => section.Rows.Children.Cast<CMAutomatedVendorEntry>())
            .ToArray();
        var iconSize = Vector2.Zero;
        var amountWidth = 0f;
        foreach (var row in rows)
        {
            foreach (var layer in row.Texture.Textures)
            {
                iconSize = Vector2.Max(iconSize, new Vector2(layer.Width, layer.Height) * row.Texture.TextureScale);
            }

            if (string.IsNullOrEmpty(row.Amount.Text))
                continue;

            row.Amount.Visible = true;
            row.Amount.SetWidth = float.NaN;
            row.Amount.Measure(new Vector2(float.PositiveInfinity));
            amountWidth = Math.Max(amountWidth, row.Amount.DesiredSize.X - row.Amount.Margin.SumHorizontal);
        }

        foreach (var row in rows)
        {
            row.Texture.SetSize = iconSize;
            row.Texture.Stretch = TextureRect.StretchMode.KeepCentered;
            row.Amount.Visible = amountWidth > 0;
            row.Amount.SetWidth = amountWidth;
        }
    }

    internal void RefreshCategories(bool tabbed)
    {
        _tabbed = tabbed;
        var categories = Sections.Children.Cast<MCVendorSectionView>()
            .Where(IsListed)
            .Select(section => section.Title.Text!)
            .Distinct()
            .ToArray();
        Categories.Visible = tabbed && categories.Length > 1;
        if (!_categories.SequenceEqual(categories))
        {
            _categories = categories;
            Categories.Clear();
            Categories.AddItem(Loc.GetString("mc-vendor-all-categories"));
            foreach (var category in categories)
            {
                Categories.AddItem(category);
            }

            var selectedIndex = Array.IndexOf(categories, _selected);
            _selected = selectedIndex < 0 ? null : categories[selectedIndex];
            Categories.Select(selectedIndex + 1);
        }

        ApplyFilter();
    }

    private void SelectCategory(int index)
    {
        Categories.Select(index);
        _selected = index == 0 ? null : _categories[index - 1];
        Catalog.SetScrollValue(default);
        ApplyFilter();
    }

    private bool IsListed(MCVendorSectionView section)
    {
        return section.Accessible && section.Rows.ChildCount > 0 &&
            (ShowEmpty.Pressed || section.Rows.Children.Cast<CMAutomatedVendorEntry>().Any(row => !row.Panel.Button.Disabled));
    }

    private void ApplyFilter()
    {
        var query = Search.Text.Trim();
        var any = false;
        foreach (var section in Sections.Children.Cast<MCVendorSectionView>())
        {
            section.Visible = IsListed(section) && (!Categories.Visible || _selected is null || section.Title.Text == _selected);
            if (!section.Visible)
                continue;

            section.Title.Visible = !Categories.Visible || _selected is null;
            section.Heading.Visible = section.Title.Visible || !string.IsNullOrEmpty(section.Allowance.Text);
            var match = section.Title.Text?.Contains(query, StringComparison.CurrentCultureIgnoreCase) == true;
            var hasMatch = false;
            foreach (var row in section.Rows.Children.Cast<CMAutomatedVendorEntry>())
            {
                row.Visible = match || row.Panel.Button.Label.Text?.Contains(query, StringComparison.CurrentCultureIgnoreCase) == true;
                hasMatch |= row.Visible;
            }

            section.Visible = hasMatch;
            any |= hasMatch;
        }

        Catalog.Visible = any;
        Empty.Visible = !any;
    }
}
