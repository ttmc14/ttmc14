using System.Linq;
using Content.Shared._MC.Serialization.Loadout.Data;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._MC.Vending.UI;

[GenerateTypedNameReferences]
public sealed partial class MCVendorQuickEquip : DefaultWindow
{
    [Dependency] private readonly IPrototypeManager _prototypes = null!;
    [Dependency] private readonly IEntityManager _entities = null!;

    public event Action<MCLoadout>? OnVend;
    private MCLoadout? _selected;

    public MCVendorQuickEquip()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);
        VendorIcon.Texture = _entities.System<SpriteSystem>().GetPrototypeIcon("MCMachineVendingQuickEquip").Default;
        VendButton.OnPressed += OnVendPressed;
    }

    private void OnVendPressed(BaseButton.ButtonEventArgs args)
    {
        if (_selected == null)
            return;

        VendButton.Disabled = true;
        Status.Text = Loc.GetString("mc-quick-equip-sent");
        Status.Visible = true;
        OnVend?.Invoke(_selected);
    }

    public void ShowLoadout(MCLoadout? loadout)
    {
        Items.DisposeAllChildren();
        _selected = loadout;
        Status.Visible = false;
        foreach (var slot in loadout?.Slots ?? [])
        {
            if (slot.Item is { } item)
                Items.AddChild(CreateItemRow(item));
        }

        var hasItems = Items.ChildCount > 0;
        ListScroll.Visible = hasItems;
        EmptyState.Visible = !hasItems;
        EmptyHint.Text = Loc.GetString(loadout == null ? "mc-quick-equip-error" : "mc-quick-equip-empty");
        VendButton.Disabled = !hasItems;
    }

    private Control CreateItemRow(MCLoadoutItem item)
    {
        var row = new BoxContainer { SeparationOverride = 6 };
        _prototypes.TryIndex(item.ProtoId, out var proto, logError: false);
        var name = proto?.Name ?? Loc.GetString("mc-quick-equip-unknown", ("id", item.ProtoId.Id));
        row.AddChild(new TextureRect
        {
            Texture = proto == null ? null : _entities.System<SpriteSystem>().GetPrototypeIcon(proto).Default,
            SetSize = new(32, 32),
            CanShrink = true,
            Stretch = TextureRect.StretchMode.KeepAspectCentered,
            VerticalAlignment = VAlignment.Top,
        });

        var children = item.Parts.SelectMany(part => part.GetContents()).ToArray();
        if (children.Length == 0)
        {
            row.AddChild(new Label { Text = name, ClipText = true, HorizontalExpand = true, ToolTip = name });
            return row;
        }

        row.AddChild(CreateContentsGroup(name, children));
        return row;
    }

    private Collapsible CreateContentsGroup(string name, MCLoadoutItem[] children)
    {
        var heading = new CollapsibleHeading(name) { ToolTip = name, MinHeight = 32 };
        heading.Label.ClipText = true;
        heading.Label.HorizontalExpand = true;
        var body = new CollapsibleBody();
        var group = new Collapsible(heading, body) { HorizontalExpand = true };
        heading.OnToggled += args =>
        {
            if (!args.Pressed || body.ChildCount != 0)
                return;

            var contents = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical };
            foreach (var child in children)
                contents.AddChild(CreateItemRow(child));
            body.AddChild(contents);
        };
        return group;
    }
}
