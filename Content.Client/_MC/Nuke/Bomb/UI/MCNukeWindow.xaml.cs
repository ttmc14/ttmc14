using Content.Shared._MC.Nuke.Bomb.Components;
using Content.Shared._MC.Nuke.Bomb.UI;
using Content.Shared.Containers.ItemSlots;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._MC.Nuke.Bomb.UI;

[GenerateTypedNameReferences]
public sealed partial class MCNukeWindow : DefaultWindow
{
    [Dependency] private readonly IEntityManager _entities = null!;
    [Dependency] private readonly IGameTiming _timing = null!;

    private readonly Dictionary<string, Button> _diskButtons = [];
    private readonly Dictionary<int, Button> _timeButtons = [];
    private EntityUid _device;
    private TimeSpan _nextUpdate;

    public MCNukeWindow()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);
    }

    internal void SetDevice(EntityUid device, Action<BoundUserInterfaceMessage> send)
    {
        _device = device;
        if (!_entities.TryGetComponent<MCNukeComponent>(device, out var bomb))
            return;

        foreach (var seconds in new[] { -10, -5, 5, 10 })
        {
            var button = new Button { Text = seconds.ToString("+0;-0") };
            button.OnPressed += _ => send(new MCNukeTimeBuiMessage(seconds));
            _timeButtons.Add(seconds, button);
            TimeControls.AddChild(button);
        }

        var slots = _entities.System<ItemSlotsSystem>();
        foreach (var id in bomb.Slots)
        {
            if (!slots.TryGetSlot(device, id, out var slot))
                continue;

            Disks.AddChild(new Label { Text = Loc.GetString(slot.Name) });
            var button = new Button();
            button.OnPressed += _ => send(new MCNukeDiskBuiMessage(id));
            _diskButtons.Add(id, button);
            Disks.AddChild(button);
        }

        Refresh(bomb);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        if (_timing.RealTime < _nextUpdate || !_entities.TryGetComponent<MCNukeComponent>(_device, out var bomb))
            return;

        _nextUpdate = _timing.RealTime + TimeSpan.FromMilliseconds(100);
        Refresh(bomb);
    }

    private void Refresh(MCNukeComponent bomb)
    {
        var slots = _entities.System<ItemSlotsSystem>();
        var available = bomb.Deployed && !bomb.Disabled && !bomb.Exploded;
        var ready = available && _diskButtons.Count == bomb.Slots.Count && _diskButtons.Count > 0;
        foreach (var (id, button) in _diskButtons)
        {
            var filled = slots.GetItemOrNull(_device, id) is not null;
            ready &= filled;
            button.Text = Loc.GetString(filled ? "mc-nuke-eject" : "mc-nuke-insert");
            button.Disabled = !available;
        }

        var active = bomb.DetonatesAt is not null;
        var anchored = _entities.GetComponent<TransformComponent>(_device).Anchored;
        Settings.Visible = ready;
        TimerButton.Disabled = !ready || !anchored || bomb.Safety;
        TimerButton.Text = Loc.GetString(active ? "mc-nuke-stop" : "mc-nuke-start");
        SafetyButton.Text = Loc.GetString(bomb.Safety ? "mc-nuke-safety-on" : "mc-nuke-safety-off");
        AnchorButton.Text = Loc.GetString(anchored ? "mc-nuke-anchored" : "mc-nuke-unanchored");
        foreach (var (seconds, button) in _timeButtons)
        {
            button.Disabled = active || (seconds < 0 ? bomb.Time <= bomb.TimeMin : bomb.Time >= bomb.TimeMax);
        }

        var now = _timing.CurTime - _entities.System<MetaDataSystem>().GetPauseTime(_device);
        var remaining = bomb.DetonatesAt is { } end ? end - now : bomb.Time;
        var secondsLeft = bomb.Exploded ? 0 : Math.Max(0, (int) Math.Ceiling(remaining.TotalSeconds));
        TimeLeftLabel.Text = $"{secondsLeft / 60:D2}:{secondsLeft % 60:D2}";
        TimeLeftProgressBar.Value = (float) (secondsLeft / Math.Max(1, bomb.Time.TotalSeconds));
        var status = bomb switch
        {
            { Exploded: true } => "mc-nuke-detonated",
            { Disabled: true } => "mc-nuke-disabled",
            _ when active => "mc-nuke-countdown",
            _ when ready => "mc-nuke-authorized",
            _ => "mc-nuke-await-disks",
        };
        StatusLabel.Text = Loc.GetString(status);
    }
}
