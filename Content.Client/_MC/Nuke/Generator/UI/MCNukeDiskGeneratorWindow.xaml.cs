using Content.Shared._MC.Nuke.Generator.Components;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._MC.Nuke.Generator.UI;

[GenerateTypedNameReferences]
public sealed partial class MCNukeDiskGeneratorWindow : DefaultWindow
{
    [Dependency] private readonly IEntityManager _entities = null!;
    [Dependency] private readonly IGameTiming _timing = null!;

    private EntityUid _generator;
    private TimeSpan _nextUpdate;

    public MCNukeDiskGeneratorWindow()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);
    }

    internal void SetGenerator(EntityUid generator)
    {
        _generator = generator;
        if (_entities.TryGetComponent<MCNukeDiskGeneratorComponent>(generator, out var comp))
        {
            OverallProgressBar.ForegroundStyleBoxOverride = new StyleBoxFlat(comp.Color);
            Refresh(comp);
        }
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        if (_timing.RealTime < _nextUpdate || !_entities.TryGetComponent<MCNukeDiskGeneratorComponent>(_generator, out var generator))
            return;

        _nextUpdate = _timing.RealTime + TimeSpan.FromMilliseconds(100);
        Refresh(generator);
    }

    private void Refresh(MCNukeDiskGeneratorComponent generator)
    {
        var complete = generator.CheckpointProgress >= 1;
        var progress = generator.CheckpointProgress.Float();
        var status = generator switch
        {
            { Disabled: true } => "mc-nuke-disabled",
            { Busy: true } when complete => "mc-nuke-generator-printing",
            { Busy: true } => "mc-nuke-generator-starting",
            { StepEndsAt: not null } => "mc-nuke-generator-running",
            _ when complete => "mc-nuke-generator-ready",
            _ when progress > 0 => "mc-nuke-generator-restart",
            _ => "mc-nuke-generator-idle",
        };

        if (generator.StepEndsAt is { } end && generator.StepDuration > TimeSpan.Zero)
        {
            var now = _timing.CurTime - _entities.System<MetaDataSystem>().GetPauseTime(_generator);
            progress += generator.StepSize.Float() * (float) Math.Clamp(1 - (end - now) / generator.StepDuration, 0, 1);
        }

        var percent = Math.Clamp((int) Math.Floor(progress * 100), 0, 100);
        OverallProgressBar.Value = percent;
        OverallProgressLabel.Text = $"{percent}%";
        StatusLabel.Text = Loc.GetString(status);
        RunButton.Text = Loc.GetString(complete ? "mc-nuke-generator-print" : "mc-nuke-generator-run");
        RunButton.Disabled = generator.Disabled || generator.Busy || generator.StepEndsAt is not null;
    }
}
