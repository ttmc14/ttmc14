using System;
using Content.Shared._MC.Engineering.Sentries.UI;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._MC.Engineering.Sentries.UI;

[GenerateTypedNameReferences]
public sealed partial class MCSentryWindow : DefaultWindow
{
    public event Action<bool>? OnRadialMode;
    public event Action<bool>? OnAlertMode;

    public MCSentryWindow()
    {
        RobustXamlLoader.Load(this);

        RadialModeCheckBox.OnToggled += OnRadialModeToggled;
        AlertModeCheckBox.OnToggled += OnAlertModeToggled;
    }

    private void OnRadialModeToggled(BaseButton.ButtonToggledEventArgs e) => OnRadialMode?.Invoke(e.Pressed);
    private void OnAlertModeToggled(BaseButton.ButtonToggledEventArgs e) => OnAlertMode?.Invoke(e.Pressed);

    public void Refresh(MCSentryBuiState state)
    {
        RoundsBar.Value = state.MaxRounds > 0 ? state.Rounds / (float) state.MaxRounds * 100f : 0f;
        RoundsLabel.Text = $"{state.Rounds} out of {state.MaxRounds}";

        IntegrityBar.Value = state.Integrity * 100f;

        IntegrityLabel.Text = $"{float.Round(state.Integrity * 100f)}%";

        RadialModeCheckBox.OnToggled -= OnRadialModeToggled;
        AlertModeCheckBox.OnToggled -= OnAlertModeToggled;

        RadialModeCheckBox.Pressed = state.RadialMode;
        AlertModeCheckBox.Pressed = state.AlertMode;

        RadialModeCheckBox.OnToggled += OnRadialModeToggled;
        AlertModeCheckBox.OnToggled += OnAlertModeToggled;
    }
}
