using System.Linq;
using Content.Shared._MC.Engineering.Beacon;
using Content.Shared._RMC14.Areas;
using Content.Shared._RMC14.TacticalMap;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client._MC.Beacon.UI;

[GenerateTypedNameReferences]
public sealed partial class MCBeaconChooseWindow : DefaultWindow
{
    [Dependency] private readonly IEntityManager _entities = null!;

    private static readonly SpriteSpecifier.Rsi BeaconIcon = new(new("/Textures/_RMC14/Interface/map_blips.rsi"), "supply");
    private static readonly SpriteSpecifier.Rsi Highlight = new(BeaconIcon.RsiPath, "background");

    public event Action<NetEntity, object?>? Selected;

    private IReadOnlyList<MCBeaconSystem.NetBeaconWithName> _entries = [];
    private NetEntity? _selected;
    private NetEntity? _grid;
    private float _retryDelay;
    private object? _payload;

    public MCBeaconChooseWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        CancelButton.StyleClasses.Add("ButtonSquare");
        CancelButton.StyleClasses.Add("ButtonColorRed");
        SubmitButton.StyleClasses.Add("ButtonSquare");
        SubmitButton.StyleClasses.Add("ButtonColorGreen");

        SubmitButton.OnPressed += _ =>
        {
            if (_selected is not { } selected)
                return;

            Selected?.Invoke(selected, _payload);
            Close();
        };
        CancelButton.OnPressed += _ => Close();

        BeaconList.OnItemSelected += args =>
        {
            var entry = _entries[args.ItemIndex];
            _selected = entry.Uid;
            SubmitButton.Disabled = false;
            ShowMap(entry.Grid, centerSelection: true);
        };
        Map.OnBlipClicked = tile =>
        {
            for (var i = 0; i < _entries.Count; i++)
            {
                if (_entries[i].Grid != _grid || _entries[i].Tile != tile)
                    continue;

                BeaconList[i].Selected = true;
                break;
            }
        };
    }

    public void OpenFor(IReadOnlyList<MCBeaconSystem.NetBeaconWithName> entries, object payload, int deliveryFee)
    {
        _payload = payload;
        _selected = null;
        OpenCentered();
        Refresh(entries, deliveryFee);
    }

    public void Refresh(IReadOnlyList<MCBeaconSystem.NetBeaconWithName> entries, int deliveryFee)
    {
        SubmitButton.Text = deliveryFee == 0
            ? Loc.GetString("generic-confirm")
            : Loc.GetString("mc-asrs-confirm-delivery-fee", ("fee", deliveryFee));
        _entries = entries;
        BeaconList.Clear();
        NetEntity? grid = entries.FirstOrDefault(entry => entry.Grid.HasValue).Grid;
        var hasSelection = false;
        foreach (var entry in entries)
        {
            var selected = entry.Uid == _selected;
            BeaconList.Add(new ItemList.Item(BeaconList) { Text = entry.Name, Selected = selected });
            if (selected)
            {
                grid = entry.Grid;
                hasSelection = true;
            }
        }

        if (!hasSelection)
            _selected = null;

        SubmitButton.Disabled = !hasSelection;
        ShowMap(grid);
    }

    private void ShowMap(NetEntity? grid, bool centerSelection = false)
    {
        if (_grid != grid)
        {
            _grid = grid;
            Map.Texture = null;
            Map.UpdateBlips(null);
        }

        if (Map.Texture == null && _entities.TryGetEntity(grid, out var uid) &&
            _entities.TryGetComponent<AreaGridComponent>(uid, out var areas))
        {
            Map.UpdateTexture((uid.Value, areas));
            centerSelection = true;
        }

        MapStatus.Visible = Map.Texture == null;
        if (MapStatus.Visible)
        {
            MapStatus.Text = Loc.GetString(_entries.Count == 0 ? "mc-asrs-no-beacons" : "mc-asrs-map-unavailable");
            return;
        }

        Map.UpdateBlips(_entries.Where(entry => entry.Grid == grid)
            .Select(entry => new TacticalMapBlip(entry.Tile, BeaconIcon, Color.LimeGreen, TacticalMapBlipStatus.Alive,
                entry.Uid == _selected ? Highlight : null, false))
            .ToArray());
        if (centerSelection && _selected is { } selected)
            Map.CenterOnPosition(_entries.First(entry => entry.Uid == selected).Tile);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        // The console state can arrive before the remote grid's area data.
        if (_grid == null || Map.Texture != null)
            return;

        _retryDelay -= args.DeltaSeconds;
        if (_retryDelay <= 0)
        {
            _retryDelay = 1f;
            ShowMap(_grid);
        }
    }
}
