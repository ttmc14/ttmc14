    private void ProcessMeleeWeaponComponent(EntityPrototype weapon)
    {
        MeleeRowsContainer.Children.Clear();
        MeleeOuterContainer.Visible = false;

        if (!weapon.TryGetComponent<MeleeWeaponComponent>(out var melee, _componentFactory))
            return;

        var damage = melee.Damage;
        if (damage.DamageDict.Count <= 0)
            return;

        foreach (var (type, value) in damage.DamageDict)
        {
            AddStatRow(MeleeRowsContainer, type, value.ToString());
        }

        MeleeOuterContainer.Visible = true;
    }

    private void AddStatRow(BoxContainer container, string label, string value)
    {
        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true
        };

        var labelControl = new RichTextLabel
        {
            HorizontalExpand = true
        };
        labelControl.SetMarkup($"[color=#888888]{label}[/color]");

        var valueControl = new RichTextLabel();
        valueControl.SetMarkup($"[bold]{value}[/bold]");

        row.AddChild(labelControl);
        row.AddChild(valueControl);
        container.AddChild(row);

        // Separator line
        var separator = new HLine
        {
            Color = Color.FromHex("#404040"),
            Thickness = 2,
            Margin = new Thickness(0, 5, 0, 5)
        };
        container.AddChild(separator);
    }
