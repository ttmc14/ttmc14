/// <summary>
/// Control for embedding a weapon into a guidebook.
/// </summary>
[UsedImplicitly, GenerateTypedNameReferences]
public sealed partial class GuideWeaponEmbed : BoxContainer, IDocumentTag, ISearchableControl, IPrototypeRepresentationControl
{
    [Dependency] private readonly ILogManager _logManager = null!;
    [Dependency] private readonly IPrototypeManager _prototype = null!;
    [Dependency] private readonly IComponentFactory _componentFactory = null!;
    [Dependency] private readonly IEntityManager _entity = null!;

    public IPrototype? RepresentedPrototype { get; private set; }

    private readonly ISawmill _sawmill;

    private EntityUid? _iconEntity;

    public GuideWeaponEmbed()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _sawmill = _logManager.GetSawmill("guidebook.weapon");

        MouseFilter = MouseFilterMode.Stop;
    }

    public GuideWeaponEmbed(string weaponId) : this()
    {
        if (_prototype.TryIndex<EntityPrototype>(weaponId, out var weapon))
            GenerateControl(weapon);
    }

    public GuideWeaponEmbed(EntityPrototype weapon) : this()
    {
        GenerateControl(weapon);
    }

    protected override void Deparented()
    {
        if (_iconEntity is not null)
            _entity.DeleteEntity(_iconEntity.Value);
    }

    public bool CheckMatchesSearch(string query)
    {
        return this.ChildrenContainText(query);
    }

    public void SetHiddenState(bool state, string query)
    {
        Visible = CheckMatchesSearch(query) ? state : !state;
    }

    public bool TryParseTag(Dictionary<string, string> args, [NotNullWhen(true)] out Control? control)
    {
        control = null;
        if (!args.TryGetValue("Weapon", out var id))
        {
            _sawmill.Error("Weapon embed tag is missing weapon prototype argument");
            return false;
        }

        if (!_prototype.TryIndex<EntityPrototype>(id, out var weapon))
        {
            _sawmill.Error("Specified weapon prototype \"" + id + "\" is not a valid entity prototype");
            return false;
        }

        GenerateControl(weapon);

        control = this;
        return true;
    }

    private void GenerateControl(EntityPrototype weapon)
    {
        RepresentedPrototype = weapon;

        if (_iconEntity != null)
            _entity.DeleteEntity(_iconEntity.Value);

        _iconEntity = _entity.SpawnEntity(weapon.ID, MapCoordinates.Nullspace);
        WeaponSprite.SetEntity(_iconEntity.Value);

        // Name and ID
        WeaponHeaderLabel.SetMarkup("[font size=12][color=#6a9a6a]ОРУЖИЕ[/color][/font]");
        WeaponName.SetMarkup($"[font size=24][bold]{weapon.Name}[/bold][/font]");
        WeaponId.SetMarkup($"[color=#6a9a6a]{weapon.ID}[/color]");
        WeaponDescription.SetMarkup(weapon.Description);

        GenerateStats(weapon);
        GenerateAmmo(weapon);
        ProcessAttachableHolderComponent(weapon);
        ProcessMeleeWeaponComponent(weapon);
    }

    private void GenerateStats(EntityPrototype weapon)
    {
        StatsRowsContainer.Children.Clear();
        StatsOuterContainer.Visible = false;

        var hasStats = false;

        if (weapon.TryGetComponent<RMCSelectiveFireComponent>(out var selectiveFire, _componentFactory))
        {
            AddStatRow(StatsRowsContainer, "Скорострельность (секунда)", $"{selectiveFire.BaseFireRate} выстр./сек");
            AddStatRow(StatsRowsContainer, "Скорострельность (минута)", $"{selectiveFire.BaseFireRate * 60} выстр./мин");
            AddStatRow(StatsRowsContainer, "Режимы огня", string.Join(", ", selectiveFire.BaseFireModes));
            //AddStatRow(StatsRowsContainer, "Бронепробитие оружия", $"{selectiveFire.ArmorPenetration}");
            AddStatRow(StatsRowsContainer, "Отдача · в упоре", $"{selectiveFire.RecoilWielded}");
            AddStatRow(StatsRowsContainer, "Отдача · с рук", $"{selectiveFire.RecoilUnwielded}");
            AddStatRow(StatsRowsContainer, "Разброс · в упоре", $"{selectiveFire.ScatterWielded * 180 / Math.PI:F2}°");
            AddStatRow(StatsRowsContainer, "Разброс · с рук", $"{selectiveFire.ScatterUnwielded * 180 / Math.PI:F2}°");
            hasStats = true;
        }

        if (weapon.TryGetComponent<GunComponent>(out var gun, _componentFactory) && gun.ShotsPerBurst > 0)
        {
            AddStatRow(StatsRowsContainer, "Очередь", $"{gun.ShotsPerBurst} выстр.");
            hasStats = true;
        }

        if (weapon.TryGetComponent<RMCWeaponAccuracyComponent>(out var accuracy, _componentFactory))
        {
            AddStatRow(StatsRowsContainer, "Точность · в упоре", $"x{accuracy.AccuracyMultiplier}");
            hasStats = true;
        }

        StatsOuterContainer.Visible = hasStats;
    }

    private void GenerateAmmo(EntityPrototype weapon)
    {
        AmmoRowsContainer.Children.Clear();
        AmmoOuterContainer.Visible = false;

        if (!weapon.TryGetComponent<ItemSlotsComponent>(out var itemSlots, _componentFactory))
            return;

        var slots = itemSlots.Slots;
        if (!slots.TryGetValue("gun_magazine", out var magSlot) || magSlot.StartingItem == null)
            return;

        if (!_prototype.TryIndex<EntityPrototype>(magSlot.StartingItem, out var magProto))
            return;

        AddStatRow(AmmoRowsContainer, "Магазин", magProto.Name);

        if (magProto.TryGetComponent<BallisticAmmoProviderComponent>(out var ballistic, _componentFactory))
        {
            AddStatRow(AmmoRowsContainer, "Ёмкость", $"{ballistic.Capacity} патронов");
        }

        AmmoOuterContainer.Visible = true;
    }

