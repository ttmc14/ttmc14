using System.Numerics;
using Content.Shared._MC.RoundInfo;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._MC.RoundInfo;

[GenerateTypedNameReferences]
public sealed partial class MCWarfareRoundInfoView : MCRoundInfoView
{
    private static readonly Color ReserveAvailableColor = Color.FromHex("#00E94E");
    private static readonly Color ReserveEmptyColor = Color.FromHex("#FFBC66");

    public override Vector2 WindowSize => new(500, 340);

    public MCWarfareRoundInfoView()
    {
        RobustXamlLoader.Load(this);
        var sprites = IoCManager.Resolve<IEntityManager>().System<SpriteSystem>();
        Emblem.Texture = sprites.Frame0(new SpriteSpecifier.Rsi(new ResPath("/Textures/_MC/Decals/decals.rsi"), "tgmc_logo"));
    }

    public override void ShowState(MCRoundInfoState state)
    {
        ModeTitle.Text = Loc.GetString(state.Title);
        Description.SetMessage(Loc.GetString(state.Description));
        SetReserve(MarinesReserve, MarinesCount, state.Reserves.Marines);
        SetReserve(XenosReserve, XenosCount, state.Reserves.Xenos);
        Briefing.Visible = state.Briefing.Count > 0;
        Briefing.SetMessage(string.Join("\n", state.Briefing));
    }

    private static void SetReserve(BoxContainer container, Label label, int? count)
    {
        container.Visible = count.HasValue;
        label.Text = count?.ToString();
        label.FontColorOverride = count == 0 ? ReserveEmptyColor : ReserveAvailableColor;
    }
}
